"use client";

import { use, useEffect, useMemo, useState } from "react";
import Link from "next/link";
import { api, label, type Audit, type Issue, type ReportFormat, type Severity } from "@/lib/api";
import { getAudit, saveAudit } from "@/lib/storage";

const SEVERITIES: Severity[] = ["critical", "high", "medium", "low", "info"];
const TABS = ["overview", "action center", "pages", "competitors", "export"] as const;
type Tab = (typeof TABS)[number];

function scoreColor(s: number) {
  return s >= 80 ? "var(--good)" : s >= 60 ? "var(--medium)" : "var(--critical)";
}

export default function AuditPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);
  const [audit, setAudit] = useState<Audit | null | undefined>(undefined);
  const [tab, setTab] = useState<Tab>("overview");

  useEffect(() => setAudit(getAudit(id)), [id]);

  if (audit === undefined) return <div className="panel muted">Loading…</div>;
  if (audit === null)
    return (
      <div className="panel">
        <h1>Audit not found</h1>
        <p className="muted">Audits are saved in the browser that ran them. <Link href="/">Run a new audit</Link>.</p>
      </div>
    );

  return (
    <>
      <section className="panel">
        <div className="hero">
          <div className="ring" style={{ background: `conic-gradient(${scoreColor(audit.overall_score ?? 0)} ${(audit.overall_score ?? 0) * 3.6}deg, var(--border) 0)` }}>
            <div>{audit.overall_score}</div>
          </div>
          <div style={{ flex: 1, minWidth: 240 }}>
            <h1 className="url">{audit.url}</h1>
            <p className="muted" style={{ margin: "4px 0 8px" }}>
              Grade <span className="grade">{audit.grade}</span> · {audit.stats.pages_crawled} pages crawled ·{" "}
              {audit.issues.length} issues · median response {audit.stats.median_response_ms ?? "–"} ms
              {audit.stats.crawl_truncated && " · crawl hit page limit"}
            </p>
            <div style={{ display: "flex", gap: 8, flexWrap: "wrap" }}>
              {SEVERITIES.map((s) => (
                <span key={s} className="pill"><span className={`sev ${s}`}>{s}</span> {audit.stats.issues_by_severity?.[s] ?? 0}</span>
              ))}
            </div>
          </div>
        </div>
      </section>

      <div className="tabs">
        {TABS.map((t) => (
          <button key={t} className={tab === t ? "active" : ""} onClick={() => setTab(t)}>{label(t)}</button>
        ))}
      </div>

      {tab === "overview" && <Overview audit={audit} onUpdate={(a) => { saveAudit(a); setAudit(a); }} />}
      {tab === "action center" && <ActionCenter issues={audit.issues} />}
      {tab === "pages" && <Pages audit={audit} />}
      {tab === "competitors" && <Competitors audit={audit} />}
      {tab === "export" && <Export audit={audit} />}
    </>
  );
}

function Overview({ audit, onUpdate }: { audit: Audit; onUpdate: (a: Audit) => void }) {
  const ai = audit.ai;
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  async function generate() {
    setBusy(true);
    setErr(null);
    try {
      onUpdate({ ...audit, ai: await api.insights(audit) });
    } catch (e) {
      setErr(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(false);
    }
  }
  return (
    <>
      <section className="panel">
        <h2>Category scores</h2>
        <div className="cards">
          {audit.category_scores.map((c) => (
            <div className="card" key={c.category}>
              <div className="k">{label(c.category)}</div>
              <div className="v" style={{ color: scoreColor(c.score) }}>{c.score}</div>
              <div className="bar"><span style={{ width: `${c.score}%`, background: scoreColor(c.score) }} /></div>
              <div className="k" style={{ marginTop: 6 }}>{c.issues} issues</div>
            </div>
          ))}
        </div>
      </section>
      {!ai && (
        <section className="panel">
          <h2>AI recommendations</h2>
          <p className="muted">Not generated for this audit yet.</p>
          <button className="btn primary" onClick={generate} disabled={busy}>{busy ? "Generating (up to ~40 s)…" : "Generate with Claude"}</button>
          {err && <p className="error">{err}</p>}
        </section>
      )}
      {ai && (
        <>
          <section className="panel">
            <h2>Executive summary</h2>
            <p>{ai.executive_summary}</p>
            <p className="muted" style={{ fontSize: 12 }}>Generated by: {ai.generated_by}</p>
          </section>
          <div className="grid2">
            <List title="Top priorities" items={ai.top_priorities} ordered />
            <List title="Quick wins (under a day)" items={ai.quick_wins} />
            <List title="Content opportunities" items={ai.content_opportunities} />
            <List title="AI search readiness" items={ai.ai_search_recommendations} />
          </div>
          <section className="panel">
            <h2>30 / 60 / 90 day roadmap</h2>
            <div className="grid3">
              {Object.entries(ai.roadmap_30_60_90).map(([k, v]) => (
                <div key={k}><h3>{label(k)}</h3><ul className="tight">{v.map((x, i) => <li key={i}>{x}</li>)}</ul></div>
              ))}
            </div>
          </section>
        </>
      )}
    </>
  );
}

function List({ title, items, ordered }: { title: string; items: string[]; ordered?: boolean }) {
  const Tag = ordered ? "ol" : "ul";
  return (
    <section className="panel">
      <h2>{title}</h2>
      {items.length ? <Tag className="tight">{items.map((x, i) => <li key={i}>{x}</li>)}</Tag> : <p className="muted">Nothing here.</p>}
    </section>
  );
}

function ActionCenter({ issues }: { issues: Issue[] }) {
  const [cat, setCat] = useState("all");
  const [sev, setSev] = useState("all");
  const [effort, setEffort] = useState("all");
  const [q, setQ] = useState("");
  const cats = useMemo(() => Array.from(new Set(issues.map((i) => i.category))), [issues]);
  const filtered = issues.filter(
    (i) =>
      (cat === "all" || i.category === cat) &&
      (sev === "all" || i.severity === sev) &&
      (effort === "all" || i.effort === effort) &&
      (!q || `${i.title} ${i.description} ${i.affected_urls.join(" ")}`.toLowerCase().includes(q.toLowerCase())),
  );
  return (
    <section>
      <div className="panel row">
        <div className="field grow"><label>Search</label><input type="text" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Issue or URL" /></div>
        <div className="field"><label>Category</label>
          <select value={cat} onChange={(e) => setCat(e.target.value)}>
            <option value="all">All</option>{cats.map((c) => <option key={c} value={c}>{label(c)}</option>)}
          </select></div>
        <div className="field"><label>Severity</label>
          <select value={sev} onChange={(e) => setSev(e.target.value)}>
            <option value="all">All</option>{SEVERITIES.map((s) => <option key={s} value={s}>{label(s)}</option>)}
          </select></div>
        <div className="field"><label>Effort</label>
          <select value={effort} onChange={(e) => setEffort(e.target.value)}>
            <option value="all">All</option><option value="low">Low</option><option value="medium">Medium</option><option value="high">High</option>
          </select></div>
      </div>
      <p className="muted">{filtered.length} issue(s), sorted by priority (impact × severity × reach ÷ effort)</p>
      {filtered.map((i) => <IssueCard key={i.id} issue={i} />)}
    </section>
  );
}

function IssueCard({ issue }: { issue: Issue }) {
  const total = (issue.evidence.total_affected as number | undefined) ?? issue.affected_urls.length;
  const evidence = Object.fromEntries(Object.entries(issue.evidence).filter(([k]) => k !== "total_affected"));
  return (
    <details className="issue">
      <summary>
        <span className={`sev ${issue.severity}`}>{issue.severity}</span>
        <strong>{issue.title}</strong>
        <span className="pill">{label(issue.category)}</span>
        <span className="meta">priority {issue.priority_score} · {total} page(s) · effort {issue.effort}</span>
      </summary>
      <div className="body">
        <p>{issue.description}</p>
        <p><strong>How to fix:</strong> {issue.recommendation}</p>
        {issue.affected_urls.length > 0 && (
          <>
            <h3>Affected URLs{total > issue.affected_urls.length ? ` (showing ${issue.affected_urls.length} of ${total})` : ""}</h3>
            <ul className="tight">
              {issue.affected_urls.slice(0, 25).map((u) => <li key={u} className="url"><a href={u} target="_blank" rel="noreferrer noopener">{u}</a></li>)}
            </ul>
            {issue.affected_urls.length > 25 && <p className="muted">…and {issue.affected_urls.length - 25} more (see CSV export)</p>}
          </>
        )}
        {Object.keys(evidence).length > 0 && (
          <>
            <h3>Evidence</h3>
            <pre className="evidence">{JSON.stringify(evidence, null, 2)}</pre>
          </>
        )}
        <p className="muted" style={{ fontSize: 12 }}>Rule: {issue.id}</p>
      </div>
    </details>
  );
}

function Pages({ audit }: { audit: Audit }) {
  const [sort, setSort] = useState<"issues" | "word_count" | "response_time_ms" | "depth">("issues");
  const pages = [...audit.pages].sort((a, b) => (b[sort] as number) - (a[sort] as number));
  return (
    <section className="panel table-wrap">
      <table>
        <thead>
          <tr>
            <th>URL</th><th>Status</th>
            {(["depth", "word_count", "response_time_ms", "issues"] as const).map((k) => (
              <th key={k} style={{ cursor: "pointer" }} onClick={() => setSort(k)}>{label(k.replace("_ms", " ms"))}{sort === k ? " ↓" : ""}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {pages.map((p) => (
            <tr key={p.url}>
              <td className="url"><a href={p.url} target="_blank" rel="noreferrer noopener">{p.url}</a><div className="muted">{p.title}</div></td>
              <td style={{ color: p.status_code >= 400 || p.status_code === 0 ? "var(--critical)" : undefined }}>{p.status_code || "err"}</td>
              <td>{p.depth}</td><td>{p.word_count}</td><td>{Math.round(p.response_time_ms)}</td><td>{p.issues}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </section>
  );
}

function Competitors({ audit }: { audit: Audit }) {
  if (!audit.competitors.length) return <div className="panel muted">No competitors were included in this audit.</div>;
  const keys = ["indexable_pages", "avg_word_count", "median_response_ms", "has_blog", "faq_pages", "sitemap_urls", "schema_types"];
  return (
    <section className="panel table-wrap">
      <table>
        <thead><tr><th>Metric</th>{audit.competitors.map((c) => <th key={String(c.url)} className="url">{String(c.url)}</th>)}</tr></thead>
        <tbody>
          {keys.map((k) => (
            <tr key={k}>
              <td>{label(k)}</td>
              {audit.competitors.map((c) => {
                const v = c[k] ?? c.error;
                return <td key={String(c.url)}>{Array.isArray(v) ? v.join(", ") || "–" : String(v ?? "–")}</td>;
              })}
            </tr>
          ))}
        </tbody>
      </table>
    </section>
  );
}

function Export({ audit }: { audit: Audit }) {
  const [busy, setBusy] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const items: [string, ReportFormat, ("issues" | "pages")?][] = [
    ["PDF report", "pdf"],
    ["HTML report", "html"],
    ["Issues CSV", "csv", "issues"],
    ["Pages CSV", "csv", "pages"],
    ["Full JSON", "json"],
  ];
  async function download(name: string, fmt: ReportFormat, kind?: "issues" | "pages") {
    setBusy(name);
    setErr(null);
    try {
      await api.report(audit, fmt, kind);
    } catch (e) {
      setErr(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(null);
    }
  }
  return (
    <section className="panel">
      <h2>Export</h2>
      <div className="row">
        {items.map(([name, fmt, kind]) => (
          <button key={name} className="btn" disabled={busy !== null} onClick={() => download(name, fmt, kind)}>
            {busy === name ? "Preparing…" : name}
          </button>
        ))}
      </div>
      {err && <p className="error">{err}</p>}
      <p className="muted">CSV opens in Excel / Google Sheets — assign rows to your developer or agency as tickets.</p>
    </section>
  );
}
