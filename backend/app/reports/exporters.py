"""Report exports: JSON, CSV (issues / pages), standalone HTML, PDF."""
from __future__ import annotations

import csv
import html
import io

from app.models import AuditResult

SEV_COLOR = {"critical": "#b42318", "high": "#d9480f", "medium": "#b08800", "low": "#2f6fb0", "info": "#6b7280"}


def to_json(r: AuditResult) -> str:
    return r.model_dump_json(indent=2)


def issues_csv(r: AuditResult) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["priority", "severity", "category", "rule_id", "issue", "affected_pages", "impact", "effort", "recommendation", "example_urls"])
    for i in r.issues:
        w.writerow([
            i.priority_score, i.severity.value, i.category.value, i.id, i.title,
            i.evidence.get("total_affected", len(i.affected_urls)), i.impact, i.effort.value,
            i.recommendation, " | ".join(i.affected_urls[:10]),
        ])
    return buf.getvalue()


def pages_csv(r: AuditResult) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["url", "status", "depth", "title", "word_count", "response_ms", "issues"])
    for p in r.pages:
        w.writerow([p.url, p.status_code, p.depth, p.title or "", p.word_count, p.response_time_ms, p.issues])
    return buf.getvalue()


def _li(items: list[str]) -> str:
    return "".join(f"<li>{html.escape(x)}</li>" for x in items)


def to_html(r: AuditResult) -> str:
    e = html.escape
    cats = "".join(
        f"<div class='card'><div class='k'>{e(c.category.value.replace('_', ' ').title())}</div>"
        f"<div class='v'>{c.score}</div><div class='s'>{c.issues} issues</div></div>"
        for c in r.category_scores
    )
    rows = "".join(
        f"<tr><td>{i.priority_score}</td><td><span class='sev' style='background:{SEV_COLOR[i.severity.value]}'>{i.severity.value}</span></td>"
        f"<td>{e(i.category.value)}</td><td><b>{e(i.title)}</b><br><small>{e(i.description)}</small>"
        f"<br><small><b>Fix:</b> {e(i.recommendation)}</small></td>"
        f"<td>{i.evidence.get('total_affected', len(i.affected_urls))}</td><td>{i.effort.value}</td></tr>"
        for i in r.issues
    )
    ai = r.ai
    ai_html = ""
    if ai:
        road = "".join(f"<h4>{e(k.replace('_', ' ').title())}</h4><ul>{_li(v)}</ul>" for k, v in ai.roadmap_30_60_90.items())
        ai_html = f"""
<h2>Executive summary</h2><p>{e(ai.executive_summary)}</p>
<div class='grid2'><div><h3>Top priorities</h3><ol>{_li(ai.top_priorities)}</ol></div>
<div><h3>Quick wins</h3><ul>{_li(ai.quick_wins)}</ul></div>
<div><h3>Content opportunities</h3><ul>{_li(ai.content_opportunities)}</ul></div>
<div><h3>AI search readiness</h3><ul>{_li(ai.ai_search_recommendations)}</ul></div></div>
<h2>30 / 60 / 90 day roadmap</h2><div class='grid3'>{road}</div>
<p class='muted'>Insights generated by: {e(ai.generated_by)}</p>"""
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>SEO Audit - {e(r.url)}</title>
<style>
body{{font:14px/1.5 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;color:#1f2328;max-width:1100px;margin:0 auto;padding:24px;background:#fff}}
h1{{margin:0}} .muted{{color:#6b7280}} .hero{{display:flex;gap:24px;align-items:center;margin:16px 0 24px}}
.score{{font-size:56px;font-weight:700}} .grade{{font-size:24px;padding:4px 14px;border-radius:8px;background:#111;color:#fff}}
.cards{{display:grid;grid-template-columns:repeat(auto-fill,minmax(140px,1fr));gap:12px}}
.card{{border:1px solid #e5e7eb;border-radius:10px;padding:12px}} .card .k{{font-size:12px;color:#6b7280}} .card .v{{font-size:28px;font-weight:700}} .card .s{{font-size:12px;color:#6b7280}}
table{{width:100%;border-collapse:collapse;margin-top:12px}} th,td{{border-bottom:1px solid #e5e7eb;padding:8px;vertical-align:top;text-align:left}}
.sev{{color:#fff;border-radius:4px;padding:1px 6px;font-size:12px}} .grid2{{display:grid;grid-template-columns:1fr 1fr;gap:16px}} .grid3{{display:grid;grid-template-columns:repeat(3,1fr);gap:16px}}
@media (max-width:700px){{.grid2,.grid3{{grid-template-columns:1fr}}}} @media print{{body{{padding:0}}}}
</style></head><body>
<h1>SEO Audit Report</h1><div class="muted">{e(r.url)} &middot; {r.created_at:%Y-%m-%d %H:%M} UTC &middot; {r.stats.get('pages_crawled', 0)} pages crawled</div>
<div class="hero"><div class="score">{r.overall_score}</div><div class="grade">{e(r.grade or '-')}</div>
<div class="muted">Overall SEO health score (0-100)</div></div>
<div class="cards">{cats}</div>
{ai_html}
<h2>All issues ({len(r.issues)}) &mdash; sorted by priority</h2>
<table><thead><tr><th>Priority</th><th>Severity</th><th>Category</th><th>Issue &amp; fix</th><th>Pages</th><th>Effort</th></tr></thead><tbody>{rows}</tbody></table>
</body></html>"""


def to_pdf(r: AuditResult) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import ListFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    e = html.escape
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm,
                            title=f"SEO Audit - {r.url}")
    ss = getSampleStyleSheet()
    small = ss["BodyText"].clone("small", fontSize=8, leading=10)
    story = [
        Paragraph("SEO Audit Report", ss["Title"]),
        Paragraph(f"{e(r.url)} &middot; {r.created_at:%Y-%m-%d} &middot; {r.stats.get('pages_crawled', 0)} pages crawled", ss["Normal"]),
        Spacer(1, 6 * mm),
        Paragraph(f"<b>Overall score: {r.overall_score}/100 (grade {e(r.grade or '-')})</b>", ss["Heading2"]),
    ]
    cat_rows = [["Category", "Score", "Issues"]] + [[c.category.value.replace("_", " ").title(), c.score, c.issues] for c in r.category_scores]
    t = Table(cat_rows, colWidths=[70 * mm, 25 * mm, 25 * mm])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#111827")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                           ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")), ("FONTSIZE", (0, 0), (-1, -1), 9)]))
    story += [t, Spacer(1, 6 * mm)]
    if r.ai:
        story += [Paragraph("Executive summary", ss["Heading2"]), Paragraph(e(r.ai.executive_summary), ss["BodyText"])]
        for heading, items in (("Top priorities", r.ai.top_priorities), ("Quick wins", r.ai.quick_wins),
                               ("Content opportunities", r.ai.content_opportunities), ("AI search readiness", r.ai.ai_search_recommendations)):
            if items:
                story += [Paragraph(heading, ss["Heading3"]),
                          ListFlowable([Paragraph(e(x), ss["BodyText"]) for x in items], bulletType="bullet")]
        for k, v in r.ai.roadmap_30_60_90.items():
            if v:
                story += [Paragraph(f"Roadmap: {k.replace('_', ' ')}", ss["Heading3"]),
                          ListFlowable([Paragraph(e(x), ss["BodyText"]) for x in v], bulletType="bullet")]
    story += [Spacer(1, 4 * mm), Paragraph(f"Issues ({len(r.issues)}), by priority", ss["Heading2"])]
    rows = [["Pri.", "Severity", "Issue / fix", "Pages"]]
    for i in r.issues:
        rows.append([
            str(i.priority_score), i.severity.value,
            Paragraph(f"<b>{e(i.title)}</b> [{e(i.category.value)}]<br/>{e(i.recommendation)}", small),
            str(i.evidence.get("total_affected", len(i.affected_urls))),
        ])
    it = Table(rows, colWidths=[14 * mm, 18 * mm, 135 * mm, 13 * mm], repeatRows=1)
    style = [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#111827")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
             ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d1d5db")), ("FONTSIZE", (0, 0), (-1, -1), 8), ("VALIGN", (0, 0), (-1, -1), "TOP")]
    for idx, i in enumerate(r.issues, start=1):
        style.append(("TEXTCOLOR", (1, idx), (1, idx), colors.HexColor(SEV_COLOR[i.severity.value])))
    it.setStyle(TableStyle(style))
    story.append(it)
    doc.build(story)
    return buf.getvalue()
